/**
 * The live-fetch resource table — ADR-0009 §1's grammar, as data.
 *
 * Ticket 05 built `pd deals list` and said the eight remaining resources would
 * be "a table entry rather than a copy of it". This file is that table. Nothing
 * about the walk, the by-id fetch, the two validation stages, the writer or the
 * exit codes is per-resource; an entry supplies four things and nothing else —
 * its plural noun, its singular `record_type`, its record schema, and the two
 * generated operations that fetch it.
 *
 * ## Five here, five elsewhere
 *
 * ADR-0009 §2 plus ADR-0017 §2 make ten resources. `pipelines`, `stages`,
 * `users` and `fields` are the cached four and arrive with ticket 08; `items`
 * is search-only and arrives with tickets 14–15. The five below are the ones
 * that fetch live on every invocation.
 *
 * ## One record schema serves both verbs
 *
 * Pipedrive titles the by-id response differently from the list response —
 * `UpsertDealResponse` against `GetDealsResponse` — so the hoist in
 * `openapi-ts.config.ts` produces two schemas per resource. They are identical
 * on all five, and `resources.test.ts` fails the build if a regeneration ever
 * makes them disagree. Until then a caller reads one shape from `list` and
 * `get` alike, which is the contract worth having.
 */

