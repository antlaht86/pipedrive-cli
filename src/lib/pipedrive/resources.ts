/** Every live resource, in the order the manifest and `--help` will list them. */
export const LIVE_RESOURCES: readonly string[] = RESOURCES.map(
  (resource) => resource.name,
);

const BY_NAME = new Map(RESOURCES.map((resource) => [resource.name, resource]));

/**
 * ADR-0009 §5: no aliases and no synonyms, so this is an exact-match lookup and
 * `people` simply is not a resource.
 */
export const resourceNamed = (name: string): Resource | undefined =>
  BY_NAME.get(name);
